package spotifysoloist

import (
	"strings"
	"unicode"
)

// Грамматика перехвата фраз. Намеренно узкая: подходит только фраза целиком, без хвостов. «Дальше» — команда плееру, а «что дальше»
// или «включи следующую песню группы кино» — нет (второе — просьба найти музыку, её слышит Яндекс). Чем меньше фраз, тем меньше
// шансов перехватить то, что относилось к чему-то другому; новые фразы добавляются в таблицу и в тест рядом.

// action — что компонент делает со Spotify по фразе.
type action int

const (
	actNone action = iota
	actPause
	actResume
	actNext
	actPrev
)

func (a action) String() string {
	switch a {
	case actPause:
		return "пауза"
	case actResume:
		return "продолжить"
	case actNext:
		return "следующий трек"
	case actPrev:
		return "предыдущий трек"
	}
	return "—"
}

// phraseTable — нормализованная фраза (строчные, без «ё», без знаков и слов-связок) → действие.
var phraseTable = buildPhrases(map[action][]string{
	actPause: {
		"пауза", "на паузу", "поставь на паузу", "поставь паузу", "поставь музыку на паузу", "поставь песню на паузу",
		"останови музыку", "останови песню", "останови воспроизведение", "останови трек", "выключи музыку", "выключи песню",
		// голого «стоп» и «останови» здесь нет: так же останавливают звонок будильника и таймера, это фраза Алисы
	},
	actResume: {
		"продолжи", "продолжай", "продолжить", "продолжи музыку", "продолжи песню", "продолжи воспроизведение", "продолжи играть",
		"играй", "играй дальше", "сними с паузы", "сними паузу", "снять с паузы", "возобнови", "возобнови музыку", "возобнови воспроизведение",
	},
	actNext: {
		"дальше", "следующая", "следующий", "следующую", "следующая песня", "следующий трек", "следующая композиция",
		"следующую песню", "следующую композицию", "включи следующую", "включи следующий", "включи следующую песню",
		"включи следующий трек", "переключи", "переключи песню", "переключи трек", "пропусти", "пропусти песню", "пропусти трек",
	},
	actPrev: {
		"назад", "предыдущая", "предыдущий", "предыдущую", "предыдущая песня", "предыдущий трек", "предыдущая композиция",
		"предыдущую песню", "предыдущую композицию", "включи предыдущую", "включи предыдущий", "включи предыдущую песню",
		"включи предыдущий трек", "верни предыдущую", "верни предыдущую песню", "вернись", "вернись назад",
	},
})

// fillers — слова, которые не меняют смысла фразы.
var fillers = map[string]bool{"алиса": true, "яндекс": true, "пожалуйста": true, "плиз": true, "ну": true, "давай": true, "слушай": true}

func buildPhrases(src map[action][]string) map[string]action {
	m := map[string]action{}
	for a, list := range src {
		for _, p := range list {
			if n := normalize(p); n != p || n == "" {
				panic("phrases: фраза не в нормальной форме: " + p)
			}
			if prev, dup := m[p]; dup && prev != a {
				panic("phrases: фраза в двух действиях: " + p)
			}
			m[p] = a
		}
	}
	return m
}

// normalize приводит фразу к виду таблицы: строчные буквы, «е» вместо «ё», знаки пропали, слова-связки убраны.
func normalize(s string) string {
	s = strings.ReplaceAll(strings.ToLower(s), "ё", "е") // сначала строчные: «Ё» заглавная
	words := strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	out := words[:0]
	for _, w := range words {
		if !fillers[w] {
			out = append(out, w)
		}
	}
	return strings.Join(out, " ")
}

// parsePhrase — действие, которое значит фраза (actNone — фраза не из грамматики).
func parsePhrase(text string) action {
	return phraseTable[normalize(text)]
}
