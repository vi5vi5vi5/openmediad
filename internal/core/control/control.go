// Package control — единая дверь для команд плееру: пауза, продолжить, дальше, назад — откуда бы они ни пришли.
//
// Команду может подать кто угодно: кнопки и жесты на колонке, кнопки наушников, голос, ответ облака, сама платформа. Каждому такому источнику
// незачем знать, какие плееры есть в сборке и чей сейчас звук. Он говорит Hub «пришло такое-то, вот откуда», а Hub решает за всех:
//
//   - чей сейчас звук (играет плеер движка, играет Яндекс.Музыка, или ничего не играет и «продолжи» достаётся тому, кто играл последним);
//   - не повтор ли это уже выполненной команды (платформа сама ответила на то же нажатие, облако продублировало фразу директивой);
//   - нужно ли подготовить автомат к запуску очереди Яндекса, который платформа затеет в ответ на жест или «играй» (ArmCarrier);
//   - кто уступает, когда второй источник заиграл (Run: заиграл плеер движка — Яндекс на паузе, и наоборот).
//
// Плеер движка (сейчас Spotify) умеет только рассказать о себе (State) и выполнить команду (Do). Не взял команду никто (играет Яндекс.Музыка или
// не играет ничего), Do возвращает false, и источник поступает как раньше: фраза идёт Алисе, кнопка наушников — платформе.
package control

import "time"

// Cmd — команда плееру.
type Cmd string

const (
	Pause  Cmd = "pause"  // поставить на паузу
	Resume Cmd = "resume" // продолжить
	Toggle Cmd = "toggle" // пауза, если играет, и продолжить, если стоит: так просят кнопки
	Next   Cmd = "next"   // следующий трек
	Prev   Cmd = "prev"   // предыдущий трек
)

func (c Cmd) String() string {
	switch c {
	case Pause:
		return "пауза"
	case Resume:
		return "продолжить"
	case Toggle:
		return "пауза/продолжить"
	case Next:
		return "следующий трек"
	case Prev:
		return "предыдущий трек"
	}
	return string(c)
}

// Origin — откуда пришла команда.
type Origin string

const (
	Speaker    Origin = "speaker"    // кнопка Алисы и жесты по верху колонки
	Headphones Origin = "headphones" // кнопки на Bluetooth-наушниках
	Voice      Origin = "voice"      // фраза после «Алиса …»
	FastVoice  Origin = "fast"       // короткая команда без «Алиса» («пауза», «дальше»): платформа распознаёт её сама
	Cloud      Origin = "cloud"      // директива в ответе облака Алисы (player_pause …): облако поняло фразу, которую мы не перехватили
	Virtual    Origin = "virtual"    // платформа сама адресовала команду плееру Spotify, которого считает своим (усыновлённая сессия)
	Arbiter    Origin = "arbiter"    // уступка звука: заиграл другой источник
	App        Origin = "app"        // изменилось само: пауза или смена трека из приложения Spotify или с другого устройства; ядро заметило это по состоянию плеера
)

func (o Origin) String() string {
	switch o {
	case Speaker:
		return "кнопка или жест на колонке"
	case Headphones:
		return "кнопка наушников"
	case Voice:
		return "голос"
	case FastVoice:
		return "короткая команда"
	case Cloud:
		return "директива облака"
	case Virtual:
		return "команда платформы"
	case Arbiter:
		return "уступка звука"
	case App:
		return "приложение или другое устройство"
	}
	return string(o)
}

// PlatformReacts говорит, видит ли то же действие платформа и ответит ли на него запуском очереди Яндекс.Музыки. На жест вперёд-назад,
// на нажатие «продолжить» и на фразу «дальше» или «играй» облако присылает audio_play, и без подготовки (ArmCarrier) Яндекс заиграл бы поверх
// Spotify. Наушники платформа не слышит: их кнопки читает только движок. Директива облака сама и есть ответ, а команда платформы — её решение.
func (o Origin) PlatformReacts() bool { return o == Speaker || o == Voice || o == FastVoice }

// State — что сейчас с плеером.
type State struct {
	// Ready — плеер готов выполнять команды (есть связь, выполнен вход). Без этого он не участвует в выборе, кому достанется команда.
	Ready bool
	// Playing — музыка идёт или вот-вот пойдёт (статус «играет»): по нему решают, чья команда «пауза».
	Playing bool
	// Sounding — звук действительно течёт в движок. Нужен для уступки звука между Spotify и Яндексом: она не должна срабатывать раньше звука.
	Sounding bool
	// Resumable — стоит на паузе, и сессия его: «продолжи» достаётся ему (в Spotify — устройство выбрано в приложении).
	Resumable bool
	// Paused — плеер на паузе (статус «на паузе»), и не важно, чья сессия: по переходу между «играет» и «на паузе» ядро замечает паузу из приложения.
	Paused bool
	// Track — какой трек сейчас в плеере (любая строка, меняющаяся вместе с треком): по смене ядро замечает, что трек перемотали в приложении.
	Track string
	// NearEnd — трек доигрывается (до конца несколько секунд): следующий трек после него — не перемотка, а обычный ход музыки.
	NearEnd bool
}

// Event — что произошло с плеером. Ядро объявляет событие, когда плеер выполнил команду через Hub, и когда состояние плеера изменилось само
// (паузу поставили в приложении, трек перемотали): по нему подсветка рисует анимацию, а источником событий может быть кто угодно.
type Event struct {
	Cmd    Cmd    // Pause, Resume, Next или Prev
	From   Origin // откуда: источник команды или App, если изменилось само
	Player string // имя плеера
}

// Player — плеер движка: компонент, который играет музыку сам и про которого платформа не знает.
type Player interface {
	// Accepts говорит, слушается ли плеер команд из этого источника (настройки компонента: голос, кнопки, плеер для платформы).
	Accepts(o Origin) bool
	// State — что сейчас с плеером.
	State() State
	// Do выполняет команду Pause, Resume, Next или Prev (Toggle ядро сводит к паузе или продолжению само). Ошибка — не вышло (нет связи): тогда
	// команда считается не выполненной, и источник поступает по-старому.
	Do(c Cmd, from Origin) error
}

// Yielder (необязательно для плеера) — ядро сообщает ему, что звук уступали из-за него или ему (для счётчика в статусе).
type Yielder interface{ Yielded() }

// Platform — что ядро знает о платформе и музыке Яндекса. Этим интерфейсом выполнен автомат mediad.Machine.
type Platform interface {
	// Playing — играет ли музыка Яндекса.
	Playing() bool
	// ArmCarrier: ближайший запуск музыки Яндекса платформой достаётся плееру движка и не играется.
	ArmCarrier(d time.Duration)
	// TakeOver останавливает музыку Яндекса, оставляя платформе её плеер уже под плеером движка; возвращает число остановленных плееров.
	TakeOver() int
}
