package control

import (
	"strings"
	"unicode"
)

// Грамматика голосовых команд плееру. Намеренно узкая: подходит только фраза целиком, без хвостов. «Дальше» — команда плееру, а «что дальше»
// или «включи следующую песню группы кино» — нет (второе — просьба найти музыку, её слышит Яндекс). Чем меньше фраз, тем меньше шансов
// перехватить то, что относилось к чему-то другому; новые фразы добавляются в таблицу и в тест рядом. Лайки, «включи музыку» и поиск по названию
// сюда не входят: это дело самого плеера (библиотека), а не управление воспроизведением.

// phraseTable — нормализованная фраза (строчные, без «ё», без знаков и слов-связок) → команда.
var phraseTable = buildPhrases(map[Cmd][]string{
	Pause: {
		"пауза", "на паузу", "поставь на паузу", "поставь паузу", "поставь музыку на паузу", "поставь песню на паузу",
		"останови музыку", "останови песню", "останови воспроизведение", "останови трек", "выключи музыку", "выключи песню",
		// голого «стоп» и «останови» здесь нет: так же останавливают звонок будильника и таймера, это фраза Алисы
	},
	Resume: {
		"продолжи", "продолжай", "продолжить", "продолжи музыку", "продолжи песню", "продолжи воспроизведение", "продолжи играть",
		"играй", "играй дальше", "сними с паузы", "сними паузу", "снять с паузы", "возобнови", "возобнови музыку", "возобнови воспроизведение",
	},
	Next: {
		"дальше", "следующая", "следующий", "следующую", "следующая песня", "следующий трек", "следующая композиция",
		"следующую песню", "следующую композицию", "включи следующую", "включи следующий", "включи следующую песню",
		"включи следующий трек", "переключи", "переключи песню", "переключи трек", "пропусти", "пропусти песню", "пропусти трек",
	},
	Prev: {
		"назад", "предыдущая", "предыдущий", "предыдущую", "предыдущая песня", "предыдущий трек", "предыдущая композиция",
		"предыдущую песню", "предыдущую композицию", "включи предыдущую", "включи предыдущий", "включи предыдущую песню",
		"включи предыдущий трек", "верни предыдущую", "верни предыдущую песню", "вернись", "вернись назад",
	},
})

// fillers — слова, которые не меняют смысла фразы.
var fillers = map[string]bool{"алиса": true, "пожалуйста": true, "плиз": true, "ну": true, "давай": true, "слушай": true}

func buildPhrases(src map[Cmd][]string) map[string]Cmd {
	m := map[string]Cmd{}
	for c, list := range src {
		for _, p := range list {
			if n := Normalize(p); n != p || n == "" {
				panic("phrases: фраза не в нормальной форме: " + p)
			}
			if prev, dup := m[p]; dup && prev != c {
				panic("phrases: фраза в двух командах: " + p)
			}
			m[p] = c
		}
	}
	return m
}

// Normalize приводит фразу к виду таблицы: строчные буквы, «е» вместо «ё», знаки пропали, слова-связки убраны.
func Normalize(s string) string {
	s = strings.ReplaceAll(strings.ToLower(s), "ё", "е") // сначала строчные: «Ё» заглавная
	words := strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	out := words[:0]
	for _, w := range words {
		if !fillers[w] {
			out = append(out, w)
		}
	}
	return strings.Join(out, " ")
}

// ParsePhrase — команда, которую значит фраза (false — фраза не из грамматики управления плеером).
func ParsePhrase(text string) (Cmd, bool) {
	c, ok := phraseTable[Normalize(text)]
	return c, ok
}

// directiveCmds — директивы облака, которыми платформа управляет плеером. На короткие фразы без слова «Алиса» («пауза», «дальше» во время
// музыки) текста локально нет, зато облако присылает директиву: её имя и есть команда.
var directiveCmds = map[string]Cmd{
	"player_pause":          Pause,
	"player_continue":       Resume,
	"player_next_track":     Next,
	"player_previous_track": Prev,
}

// ParseVirtual — команда, которую значит команда платформы виртуальному плееру движка (pause, release, play): пауза или освобождение
// (кнопка, «Алиса, пауза» с плеером в контексте) ставят плеер на паузу, play продолжает. false — другая команда, плееру не передаётся.
func ParseVirtual(cmd string) (Cmd, bool) {
	switch cmd {
	case "pause", "release":
		return Pause, true
	case "play":
		return Resume, true
	}
	return "", false
}

// ParseDirective — команда, которую значит имя директивы ответа облака (false — директива не про плеер).
func ParseDirective(name string) (Cmd, bool) {
	c, ok := directiveCmds[name]
	return c, ok
}
