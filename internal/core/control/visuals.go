package control

// Кто показывает действие на колонке. У штатной музыки паузу и перемотку прошивка сопровождает анимацией на дисплее с часами и на кольце
// логотипа. У плеера движка так выходит не всегда: зависит от того, каким путём пришла команда. Эти правила — наблюдения за прошивкой
// (журнал платформы maind.log, 01.11.2026), и живут они здесь, в ядре, чтобы компоненту вывода не нужно было разбирать источники команд:
// он смотрит на Event.PlatformDisplay и Event.PlatformRing и рисует своё только там, где прошивка промолчит.
//
//   - короткая команда без «Алиса» (FastVoice): платформа отвечает локальным сценарием с анимацией (draw_animation_directive);
//   - директива облака (Cloud): анимация приходит в том же ответе;
//   - команда платформы принятому ею плееру (Virtual): платформа выполняет её как команду своему плееру и рисует сама;
//   - кнопка колонки, пауза (Speaker + Pause): пауза локальна, анимация дисплея приходит сразу; кольцо при этом молчит;
//   - кнопка колонки и фраза с «Алиса», перемотка и продолжение: платформа спрашивает облако, в ответе (audio_play) анимации нет;
//   - фраза с «Алиса», пауза: диалог отменяется раньше ответа, анимации не будет;
//   - кнопки наушников, приложение источника, команда извне: прошивка о действии не знает;
//   - музыка платформы (Player == OwnerPlatform): всё показывает прошивка, как у штатной музыки.

// Mark возвращает событие с отметками «покажет прошивка» (PlatformDisplay, PlatformRing). События, которые объявляет Hub, уже отмечены;
// функция нужна тестам компонентов вывода и тем, кто собирает событие сам.
func Mark(e Event) Event {
	e.PlatformDisplay, e.PlatformRing = platformDisplay(e), platformRing(e)
	return e
}

// platformDisplay — прошивка сама покажет событие на дисплее.
func platformDisplay(e Event) bool {
	if e.Player == OwnerPlatform {
		return true
	}
	switch e.From {
	case FastVoice, Cloud, Virtual:
		return true
	case Speaker:
		return e.Cmd == Pause
	}
	return false
}

// platformRing — прошивка сама покажет событие на кольце логотипа.
func platformRing(e Event) bool {
	if e.Player == OwnerPlatform {
		return true
	}
	switch e.From {
	case FastVoice, Cloud, Virtual:
		return true
	}
	return false
}
